import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
const app = express();
const port = Number(process.env.PORT ?? 4000);
const frontendOrigin = process.env.FRONTEND_ORIGIN ?? 'http://localhost:5173';
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: frontendOrigin }));
app.use(express.json({ limit: '100kb' }));
app.get('/api/health', (_req, res) => res.status(200).json({status:'ok',service:'dia-infect-api',version:'0.1.0',timestamp:new Date().toISOString()}));
app.use((_req, res) => res.status(404).json({error:'NOT_FOUND',message:'Route not found.'}));
app.listen(port, () => console.log(`DiaInfect API listening on http://localhost:${port}`));
